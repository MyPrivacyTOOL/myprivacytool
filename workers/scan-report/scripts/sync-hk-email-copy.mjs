// Generates lib/hkSpamEmail.generated.js from src/data/hkSpamEmailCopy.json (the day-10 email strings, reviewed with the page copy in MPC-7542).
// Same reason as sync-guides.mjs: the Worker bundler cannot take a JSON import with attributes. CI runs this before test + deploy.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const src = fileURLToPath(new URL('../../../src/data/hkSpamEmailCopy.json', import.meta.url));
const out = fileURLToPath(new URL('../lib/hkSpamEmail.generated.js', import.meta.url));
const copy = JSON.parse(readFileSync(src, 'utf8'));
writeFileSync(out, `// GENERATED by scripts/sync-hk-email-copy.mjs from src/data/hkSpamEmailCopy.json - do not edit by hand.\nexport default ${JSON.stringify(copy, null, 2)};\n`);
console.log('hkSpamEmail.generated.js: languages', Object.keys(copy).join(','));
