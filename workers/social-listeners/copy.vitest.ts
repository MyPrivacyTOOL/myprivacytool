// @vitest-environment node
// MPC-7251 follow-up: the Telegram bot's English wording must only describe what the free scan really does.
// Same idea as the email over-promise test (MPC-7469): the old claims are blocked, new claims need a deliberate edit.
import { describe, expect, it } from "vitest";
import en from "../../locales/en/main.json";
import { composeReply } from "./src/reply";

const ALL = Object.values(en).join("\n");

describe("bot English wording does not over-promise", () => {
  it.each([
    ["claims findings about the person", /publicly known about you right now/i],
    ["claims the Telegram profile name is visible", /visible from your Telegram profile/i],
    ["claims a phone link", /possibly linked to this account/i],
    ["claims cross-platform links were detected", /links detected/i],
    ["claims a broker count", /\b40\+|estimated \d+/i],
    ["claims data broker exposure was found", /data broker exposure/i],
    ["claims brokers are searched live", /what data brokers know about you/i],
    ["claims a report is generated by the chat", /being generated/i],
    ["claims a scan time in seconds or minutes", /\b\d+\s*(seconds?|minutes?)\b/i],
    ["says no signup/email is needed", /no signup/i],
    ["claims nothing is saved", /haven't saved|not saved|don't save/i],
  ])("does not contain: %s", (_name, re) => expect(ALL).not.toMatch(re));

  it("says what the bot can see and keep, what it cannot see, and that brokers are not searched yet", () => {
    expect(en["bot.first_hexagon.question"]).toMatch(/public details of your Telegram profile/);
    expect(en["bot.first_hexagon.question"]).toMatch(/don't get your phone number or contacts/);
    expect(en["bot.first_hexagon.question"]).toMatch(/up to 90 days/);
    expect(en["bot.first_hexagon.question"]).not.toMatch(/can't see your Telegram profile/);
    expect(en["bot.first_hexagon.brokers"]).toMatch(/not searched yet/i);
  });
  it("tells the user an email is asked for", () => {
    expect(en["bot.unknown.free"]).toMatch(/email/i);
    expect(en["bot.confirmed_y.duration"]).toMatch(/email/i);
  });
  it("says plainly that contact details are not taken in chat yet, and does not claim anything about saving", () => {
    expect(en["bot.contact_unsupported"]).toMatch(/can't take an email address or phone number/);
    expect(en["bot.contact_unsupported"]).toMatch(/please don't send one here/);
    expect(en["bot.contact_unsupported"]).not.toMatch(/saved/i);
  });
  it("keeps the Y and N prompts and the scan link", () => {
    expect(en["bot.first_hexagon.reply_y"]).toMatch(/\*Y\*/);
    expect(en["bot.first_hexagon.reply_n"]).toMatch(/\*N\*/);
    expect(en["bot.confirm_prompt"]).toMatch(/\*Y\*.*\*N\*/);
    expect(composeReply(["bot.confirmed_y.title", "bot.confirmed_y.generating", "bot.confirmed_y.cta", "bot.confirmed_y.duration"], "en")).toContain("https://myprivacytool.io/scan");
  });
});
