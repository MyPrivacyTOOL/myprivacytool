// MPC-8689: builds everything that is derived from shared/hexagon-registry/hexagons-366.json (the approved 366-hexagon discovery, risk tiers
// approved 2026-10-28): catalogue.js (the registry copy), public/footprint/hexagons-366.json (the /footprint/ dataset) and, only when it does not
// exist yet, the Supabase seed migration. Run: node scripts/build-hexagon-catalogue.mjs. The /hexagon/<name>/ pages are built at deploy time by
// scripts/generate-hexagon-pages.mjs from catalogue.js.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(readFileSync(path.join(ROOT, 'shared/hexagon-registry/hexagons-366.json'), 'utf8'));
const items = data.items;

// Channel code = the prefix used in the hexagon ids (tg.username -> TG). Web and email ids have no dotted prefix.
const CODES = { web: 'WEB', email: 'EM', sms: 'SMS', whatsapp: 'WA', telegram: 'TG', x: 'X', instagram: 'IG', messenger: 'FB', linkedin: 'LI', discord: 'DC', reddit: 'RD', youtube: 'YT', github: 'GH', tiktok: 'TT', line: 'LINE', kakaotalk: 'KK', wechat: 'WC', qq: 'QQ', zalo: 'ZL', viber: 'VB', weibo: 'WB', douyin: 'DY', naver: 'NV', phone: 'CALL', fax: 'FAX', letter: 'POST' };
const channels = [];
for (const i of items) if (!channels.find((c) => c.key === i.channel)) channels.push({ key: i.channel, code: CODES[i.channel], label: i.channel_label, group: i.group });
if (channels.some((c) => !c.code)) throw new Error('channel without a code');

const rows = items.map((i) => ({ id: i.id, slug: i.slug, channel: i.channel, group: i.group, arrival: i.arrival, risk: i.risk, label: i.label, reveals: i.reveals ?? '', field: i.field ?? '', status: i.status, access: i.access, source: i.source ?? '' }));
const js = `// GENERATED by scripts/build-hexagon-catalogue.mjs from hexagons-366.json (MPC-8689). Do not edit by hand.
// ${items.length} hexagons across ${channels.length} channels. status "defined" = already in the code (web registry.js, EMAIL_HEXAGONS, TELEGRAM_HEXAGONS);
// "new" = found in the platform documentation, not built and not measured. New items never count in scanCounts or the exposure score.
export const CATALOGUE_CHANNELS = ${JSON.stringify(channels, null, 1)};

export const CATALOGUE_VERSION = ${JSON.stringify(data.risk_tiers_approved ?? '2026-10-28')};

export const HEXAGON_CATALOGUE = ${JSON.stringify(rows, null, 1)};
`;
writeFileSync(path.join(ROOT, 'shared/hexagon-registry/catalogue.js'), js);
const { EXTRA_HEXAGON_IDS } = await import('../shared/hexagon-registry/channels.js'); // built extras are checked, so they are not labelled "not checked yet"
const extras = new Set(EXTRA_HEXAGON_IDS);

// /footprint/ dataset: merged into the built-in web items by id (the built-in ones keep their emoji, example and confidence; this file supplies the approved risk tier).
const shortChannel = (i) => (i.channel === 'web' ? 'Web' : i.channel_label.replace(/\s*\(.*\)$/, ''));
const footprint = items.map((i) => ({
  id: i.id, label: i.label, group: i.group, box: shortChannel(i), channel: shortChannel(i), sens: i.risk, cap: i.reveals ?? '',
  val: i.status === 'new' && !extras.has(i.id) ? 'Not checked by MPT yet. Found in the platform documentation.' : '', arrival: i.arrival, status: i.status, slug: i.slug,
}));
writeFileSync(path.join(ROOT, 'public/footprint/hexagons-366.json'), JSON.stringify(footprint));

const mig = path.join(ROOT, 'supabase/migrations/20261028180000_mpc_8689_hexagon_catalogue.sql');
if (!existsSync(mig)) {
  const q = (s) => `'${String(s ?? '').replace(/'/g, "''")}'`;
  const vals = items.map((i) => `(${[i.id, i.channel, i.group, CODES[i.channel], i.arrival, i.risk, i.label, i.reveals, i.field, i.status, i.access, i.source, i.slug].map(q).join(', ')})`).join(',\n');
  writeFileSync(mig, `-- MPC-8689: the complete footprint catalogue (366 hexagons, 26 channels). Read-only reference data for the website.
-- Does not touch hexagon_scores or any scan table. New ("new") rows are documentation finds that MPT does not check yet and never count in a score.
create table if not exists public.hexagon_catalogue (
  id text primary key,
  slug text not null unique,
  channel text not null,
  channel_group text not null,
  code text not null,
  arrival text not null check (arrival in ('A','B','C','D')),
  risk text not null check (risk in ('high','medium','low')),
  label text not null,
  reveals text not null default '',
  field text not null default '',
  status text not null check (status in ('defined','new')),
  access text not null default '',
  source_url text not null default '',
  catalogue_version text not null default ${q(data.risk_tiers_approved ?? '2026-10-28')},
  updated_at timestamptz not null default now()
);
create index if not exists hexagon_catalogue_channel_idx on public.hexagon_catalogue (channel);
create index if not exists hexagon_catalogue_risk_idx on public.hexagon_catalogue (risk);

alter table public.hexagon_catalogue enable row level security;
drop policy if exists hexagon_catalogue_read on public.hexagon_catalogue;
create policy hexagon_catalogue_read on public.hexagon_catalogue for select to anon, authenticated using (true);
revoke insert, update, delete, truncate on public.hexagon_catalogue from anon, authenticated;
grant select on public.hexagon_catalogue to anon, authenticated;

insert into public.hexagon_catalogue (id, channel, channel_group, code, arrival, risk, label, reveals, field, status, access, source_url, slug) values
${vals}
on conflict (id) do update set channel = excluded.channel, channel_group = excluded.channel_group, code = excluded.code, arrival = excluded.arrival,
  risk = excluded.risk, label = excluded.label, reveals = excluded.reveals, field = excluded.field, status = excluded.status, access = excluded.access,
  source_url = excluded.source_url, slug = excluded.slug, updated_at = now();
`);
}
console.log(`catalogue: ${items.length} hexagons, ${channels.length} channels`);
