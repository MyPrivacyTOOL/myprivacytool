// MPC-8689: builds everything that is derived from shared/hexagon-registry/register-662.json, the canonical 662-row
// footprint register (Notion IDs 1-662, verified 2026-11-26; owner decision 2026-11-26 moved the public footprint from
// 368 to 662). It writes catalogue.js (the registry copy) and public/footprint/hexagons-662.json (the /footprint/ dataset).
// Run: node scripts/build-hexagon-catalogue.mjs. The /hexagon/<name>/ pages are built at deploy time by
// scripts/generate-hexagon-pages.mjs from catalogue.js.
//
// hexagons-366.json is NOT edited: it stays the approved 2026-10-28 discovery (366 items + 2 records items) and the
// source of the decision/plan fields. The register snapshot carries those fields forward for the matched items.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const items = JSON.parse(readFileSync(path.join(ROOT, 'shared/hexagon-registry/register-662.json'), 'utf8'));
if (items.length !== 662) throw new Error(`register-662.json must hold 662 rows, found ${items.length}`);
if (new Set(items.map((i) => i.id)).size !== 662) throw new Error('register-662.json ids must be unique');
if (new Set(items.map((i) => i.slug)).size !== 662) throw new Error('register-662.json slugs must be unique');

// Keep the original catalogue invariant: walk the channels in arrival order (A first). Rows whose arrival class is
// still unrecorded go last, in register order; the sort is stable, so the register order is kept inside a class.
const ARRIVAL_RANK = { A: 0, B: 1, C: 2, D: 3 };
items.sort((a, b) => (ARRIVAL_RANK[a.arrival] ?? 4) - (ARRIVAL_RANK[b.arrival] ?? 4));

// Channel code = the prefix used in the hexagon ids (tg.username -> TG). Web and email ids have no dotted prefix.
const CODES = {
  web: 'WEB', email: 'EM', sms: 'SMS', whatsapp: 'WA', telegram: 'TG', x: 'X', instagram: 'IG', messenger: 'FB',
  linkedin: 'LI', discord: 'DC', reddit: 'RD', youtube: 'YT', github: 'GH', tiktok: 'TT', line: 'LINE', kakaotalk: 'KK',
  wechat: 'WC', qq: 'QQ', zalo: 'ZL', viber: 'VB', weibo: 'WB', douyin: 'DY', naver: 'NV', phone: 'CALL', fax: 'FAX',
  letter: 'POST', brokers: 'DB',
  // channels imported into the register after the 2026-10-28 discovery (MPC-11319, 2026-11-25)
  slack: 'SL', mastodon: 'MD', twitch: 'TW', imessage: 'IMSG', snapchat: 'SC', bluesky: 'BS',
  // rows the register files as several channels at once (rules page: do not guess a platform)
  cross: 'XC',
};
const channels = [];
for (const i of items) if (!channels.find((c) => c.key === i.channel)) channels.push({ key: i.channel, code: CODES[i.channel], label: i.channel_label, group: i.group });
if (channels.some((c) => !c.code)) throw new Error('channel without a code: ' + channels.filter((c) => !c.code).map((c) => c.key).join(', '));

const rows = items.map((i) => ({
  id: i.id, slug: i.slug, channel: i.channel, group: i.group, arrival: i.arrival, risk: i.risk, label: i.label,
  reveals: i.reveals ?? '', field: i.field ?? '', status: i.status, access: i.access ?? '', source: i.source ?? '',
  ...(i.code_ids ? { code_ids: i.code_ids } : {}), ...(i.note ? { note: i.note } : {}),
  ...(i.plan ? { plan: i.plan, plan_decision: i.plan_decision, plan_reason: i.plan_reason } : {}),
  ...(i.decision ? { decision: i.decision, decision_reason: i.decision_reason, decided: i.decided } : {}),
}));
const js = `// GENERATED by scripts/build-hexagon-catalogue.mjs from register-662.json (MPC-8689, owner decision 2026-11-26). Do not edit by hand.
// ${items.length} hexagons across ${channels.length} channels. status "defined" = already in the code (web registry.js, EMAIL_HEXAGONS, TELEGRAM_HEXAGONS);
// "new" = catalogued in the footprint register but not built and not measured. New items never count in scanCounts or the exposure score.
export const CATALOGUE_CHANNELS = ${JSON.stringify(channels, null, 1)};

export const CATALOGUE_VERSION = ${JSON.stringify('register-2026-11-26')};

export const HEXAGON_CATALOGUE = ${JSON.stringify(rows, null, 1)};
`;
writeFileSync(path.join(ROOT, 'shared/hexagon-registry/catalogue.js'), js);
const { EXTRA_HEXAGON_IDS } = await import('../shared/hexagon-registry/channels.js'); // built extras are checked, so they are not labelled "not checked yet"
const extras = new Set(EXTRA_HEXAGON_IDS);

// /footprint/ dataset: merged into the built-in web items by id (the built-in ones keep their emoji, example and confidence; this file supplies the approved risk tier).
const shortChannel = (i) => (i.channel === 'web' ? 'Web' : i.channel_label.replace(/\s*\(.*\)$/, ''));
const footprint = items.map((i) => ({
  id: i.id, label: i.label, group: i.group, box: shortChannel(i), channel: shortChannel(i), sens: i.risk, cap: i.reveals ?? '',
  val: i.status === 'new' && !extras.has(i.id) ? 'Not checked by MPT yet. Found in the platform documentation.' : '', arrival: i.arrival, status: i.status, slug: i.slug,
}));
writeFileSync(path.join(ROOT, 'public/footprint/hexagons-662.json'), JSON.stringify(footprint));
console.log(`catalogue: ${items.length} hexagons, ${channels.length} channels`);
