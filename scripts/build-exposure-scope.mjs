// MPC-11569 / MPC-11622: generates shared/exposure/channels/scope.generated.js, the in-scope data points of the WEB and EMAIL channels for the shared exposure core
// (shared/exposure/exposure.js, rules page "MPT > Exposure scoring - the rules for every channel", decided 2026-11-27). Same shape the Telegram channel derives for itself:
//   * scope = the data points the channel CAN observe: the web hexagons whose truth level is not "cannot_be_checked" (47) and the built email checks (6). The 7 web hexagons
//     the site can never observe are not in N (as Telegram's 5 never-evaluated fields are not in its 25); they are listed in NOT_OBSERVABLE_WEB.
//   * tier = the APPROVED risk tier from the catalogue (risk tiers approved 2026-10-28), low / medium / high. NOT the registry's older `truth.sensitivity` (differs for 29 of the 60).
//   * group = `settings` ("Your settings") when a person can change it, else `base` ("Always sent"). Web: the nine hexagons with a typed fix block (FIX_BLOCK_IDS in
//     src/lib/hexagonFix.ts, approved MPC-8733; a vitest keeps this list equal to it). Email: the Gravatar and Libravatar pictures and the GitHub commit email are changeable;
//     the address itself, its provider and its domain record are not under the person's control.
// The catalogue is about 310 KB, so this small generated file is what Workers import. Run: node scripts/build-exposure-scope.mjs  (--check exits 1 if the file is stale).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { HEXAGONS, EMAIL_HEXAGONS } from '../shared/hexagon-registry/registry.js';
import { HEXAGON_CATALOGUE } from '../shared/hexagon-registry/catalogue.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = path.join(ROOT, 'shared/exposure/channels/scope.generated.js');
export const CHANGEABLE_WEB = ['webrtc-leak', 'canvas-fingerprint', 'webgl-fingerprint', 'audio-fingerprint', 'location', 'isp', 'language-mismatch', 'demographic', 'user-profile'];
export const CHANGEABLE_EMAIL = ['email-profile', 'email-libravatar', 'email-github-commits'];
const cat = new Map(HEXAGON_CATALOGUE.map((i) => [i.id, i]));
const tierOf = (id) => { const t = cat.get(id)?.risk; if (!['low', 'medium', 'high'].includes(t)) throw new Error(`no approved risk tier in the catalogue for ${id}`); return t; };

export function render() {
  const web = HEXAGONS.filter((h) => h.truth.level !== 'cannot_be_checked');
  const email = EMAIL_HEXAGONS.filter((h) => h.build_status === 'built');
  const notObservable = HEXAGONS.filter((h) => h.truth.level === 'cannot_be_checked').map((h) => h.id);
  const notBuilt = Object.fromEntries(EMAIL_HEXAGONS.filter((h) => h.build_status !== 'built').map((h) => [h.id, h.build_status ?? 'not built']));
  for (const id of CHANGEABLE_WEB) if (!web.some((h) => h.id === id)) throw new Error(`changeable web id ${id} is not an observable web hexagon`);
  for (const id of CHANGEABLE_EMAIL) if (!email.some((h) => h.id === id)) throw new Error(`changeable email id ${id} is not a built email check`);
  const row = (changeable) => (h) => `  { id: '${h.id}', label: ${JSON.stringify(h.label)}, tier: '${tierOf(h.id)}', group: '${changeable.includes(h.id) ? 'settings' : 'base'}' },`;
  return `// GENERATED by scripts/build-exposure-scope.mjs (MPC-11569 / MPC-11622). Do not edit by hand. The in-scope data points of the web and email channels for the shared
// exposure core, with the approved risk tier and whether a person can change them. See the generator for how each is decided. ${web.length} web + ${email.length} email.
export const WEB_FIELDS = Object.freeze([
${web.map(row(CHANGEABLE_WEB)).join('\n')}
].map((f) => Object.freeze(f)));

export const EMAIL_FIELDS = Object.freeze([
${email.map(row(CHANGEABLE_EMAIL)).join('\n')}
].map((f) => Object.freeze(f)));

/** Web hexagons the site can never observe: not data points this channel can reveal, so not in N and not scored. */
export const NOT_OBSERVABLE_WEB = Object.freeze(${JSON.stringify(notObservable)});

/** Email hexagons that exist in the registry but are not built: not scored, not Live. id -> the registry's build status. */
export const EMAIL_NOT_BUILT = Object.freeze(${JSON.stringify(notBuilt)});
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = render();
  if (process.argv.includes('--check')) {
    if (readFileSync(OUT, 'utf8') !== out) { console.error('shared/exposure/channels/scope.generated.js is stale: run node scripts/build-exposure-scope.mjs'); process.exit(1); }
    console.log('scope.generated.js is up to date');
  } else { writeFileSync(OUT, out); console.log(`wrote ${path.relative(ROOT, OUT)}`); }
}
