// MPC-11569: generates shared/hexagon-registry/scopeV3.js, the in-scope data points of exposure-v3 (the owner's scoring rules, decided 2026-11-27):
//   * scope = every hexagon the web scan or the email report CAN observe: the web hexagons whose truth level is not "cannot_be_checked" (47) + the built email checks (6);
//     the 7 the site can never observe are not data points this channel can reveal, so they are not in N (same as Telegram: 25 evaluated of 30, rules page);
//   * tier = the APPROVED risk tier from the catalogue (hexagons-366.json, approved 2026-10-28), low 1 / medium 2 / high 3 (NOT the registry's older `truth.sensitivity`, which differs for 29 of the 60);
//   * changeable = depends on something the person can change ("Your settings"); everything else is "Always sent" (the floor). Web: the nine hexagons with a typed fix block
//     (FIX_BLOCK_IDS in src/lib/hexagonFix.ts, approved MPC-8733; a vitest keeps this list equal to it). Email: the three a person can remove or change (their Gravatar and
//     Libravatar pictures, their GitHub commit email); the address itself, its provider and its domain record are not under their control.
// The catalogue is about 310 KB, so this small generated file is what the Workers import. Run: node scripts/build-scope-v3.mjs  (--check exits 1 if the file is stale).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { HEXAGONS } from '../shared/hexagon-registry/registry.js';
import { HEXAGON_CATALOGUE } from '../shared/hexagon-registry/catalogue.js';
import { EMAIL_SCORED_HEXAGONS } from '../shared/hexagon-registry/scoreV2.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = path.join(ROOT, 'shared/hexagon-registry/scopeV3.js');
export const CHANGEABLE_WEB = ['webrtc-leak', 'canvas-fingerprint', 'webgl-fingerprint', 'audio-fingerprint', 'location', 'isp', 'language-mismatch', 'demographic', 'user-profile'];
export const CHANGEABLE_EMAIL = ['email-profile', 'email-libravatar', 'email-github-commits'];
const TIER = { low: 1, medium: 2, high: 3 };
const cat = new Map(HEXAGON_CATALOGUE.map((i) => [i.id, i]));
const tierOf = (id) => { const t = TIER[cat.get(id)?.risk]; if (!t) throw new Error(`no approved risk tier in the catalogue for ${id}`); return t; };

export function render() {
  const web = HEXAGONS.filter((h) => h.truth.level !== 'cannot_be_checked');
  const notObservable = HEXAGONS.filter((h) => h.truth.level === 'cannot_be_checked').map((h) => h.id);
  for (const id of CHANGEABLE_WEB) if (!web.some((h) => h.id === id)) throw new Error(`changeable web id ${id} is not an observable web hexagon`);
  for (const id of CHANGEABLE_EMAIL) if (!EMAIL_SCORED_HEXAGONS.some((h) => h.id === id)) throw new Error(`changeable email id ${id} is not a built email check`);
  const row = (channel, changeable) => (h) => `  { id: '${h.id}', channel: '${channel}', tier: ${tierOf(h.id)}, changeable: ${changeable.includes(h.id)} },`;
  return `// GENERATED by scripts/build-scope-v3.mjs (MPC-11569). Do not edit by hand. The in-scope data points of exposure-v3 with their approved risk tier and whether
// a person can change them. See the generator for how each is decided. ${web.length} web + ${EMAIL_SCORED_HEXAGONS.length} email = ${web.length + EMAIL_SCORED_HEXAGONS.length}.
export const SCOPE_V3 = Object.freeze([
${web.map(row('web', CHANGEABLE_WEB)).join('\n')}
${EMAIL_SCORED_HEXAGONS.map(row('email', CHANGEABLE_EMAIL)).join('\n')}
].map((r) => Object.freeze(r)));

/** Web hexagons the site can never observe: not data points this channel can reveal, so not in N and not scored. */
export const NOT_OBSERVABLE_WEB = Object.freeze(${JSON.stringify(notObservable)});
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = render();
  if (process.argv.includes('--check')) {
    if (readFileSync(OUT, 'utf8') !== out) { console.error('shared/hexagon-registry/scopeV3.js is stale: run node scripts/build-scope-v3.mjs'); process.exit(1); }
    console.log('scopeV3.js is up to date');
  } else { writeFileSync(OUT, out); console.log(`wrote ${path.relative(ROOT, OUT)}`); }
}
