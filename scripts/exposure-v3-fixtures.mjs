// MPC-11569: the published fixture table for exposure-v3 (rules page section 8: "Publish the fixture table with the change"). Synthetic profiles through the real scoring code.
// Run: node scripts/exposure-v3-fixtures.mjs  (writes docs/exposure-v3-fixtures-mpc-11569.md)   --check exits 1 if the committed file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { computeExposureV3, scopeFor, crossChannel, crossChannelLine } from '../shared/hexagon-registry/scoreV3.js';
import { WEB_PROFILES, EMAIL_PROFILES } from '../shared/hexagon-registry/scoreV3.fixtures.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = path.join(ROOT, 'docs/exposure-v3-fixtures-mpc-11569.md');
const table = (profiles, channel) => {
  const rows = profiles.map((p) => {
    const r = computeExposureV3(p.items, { channel, final: true });
    const v = (x) => (x === null ? 'no score' : String(x));
    return `| ${p.name} | ${v(r.exposure)} | ${r.fields.returned} of ${r.fields.total} | ${v(r.achievable_percent)}${r.achievable_percent === null ? '' : '%'} | ${r.stack ? `${r.stack.always_sent} + ${r.stack.settings}` : 'n/a'} | ${r.recoverable_points} |`;
  });
  return `| Profile | Exposure | Fields returned | Position in achievable range | Always sent + your settings (points) | Points recoverable |\n|---|---|---|---|---|---|\n${rows.join('\n')}`;
};
export function render() {
  const w = scopeFor('web'); const e = scopeFor('email');
  const wTot = w.reduce((a, r) => a + r.tier, 0); const eTot = e.reduce((a, r) => a + r.tier, 0);
  const wf = computeExposureV3(WEB_PROFILES[3].items, { channel: 'web' }); const ef = computeExposureV3(EMAIL_PROFILES[1].items, { channel: 'email' });
  return `# exposure-v3 fixtures (MPC-11569)

GENERATED by \`node scripts/exposure-v3-fixtures.mjs\`. Do not edit by hand. Synthetic profiles through the real code (\`shared/hexagon-registry/scoreV3.js\`), as the scoring rules page requires (section 8). The score is **within-channel only**: web and email are scored separately and never combined.

How to read it: *Exposure* = tier weight of the fields that came back / tier weight of every field in scope, as a whole number (fixed denominator, nothing returned counts 0). *Fields returned* is the unweighted count beside it. *Always sent* is the floor (the platform, not your settings); *your settings* is the part a person can change. *Position in achievable range* = the share of the changeable weight that came back (0% = nothing changeable is exposed). *Points recoverable* = what the score would drop if every changeable field that came back were fixed. No band is shown: bands are not calibrated for a channel with a floor (rule 7).

## Web (${w.length} data points in scope, tier weight ${wTot}; floor ${computeExposureV3(WEB_PROFILES[0].items).floor})

${table(WEB_PROFILES, 'web')}

## Email (${e.length} data points in scope, tier weight ${eTot}; floor ${computeExposureV3(EMAIL_PROFILES[0].items, { channel: 'email' }).floor})

${table(EMAIL_PROFILES, 'email')}

## Across channels (the only combined figure)

Example, web W3 with email E2: ${wf ? `\`${crossChannelLine(crossChannel([wf, ef]))}\`` : ''}. Never an average, never a ranking of the two exposures.

## What the tests assert on these profiles (\`shared/hexagon-registry/scoreV3.test.mjs\`)

* **Monotonic:** hardening a setting never raises the score. Exhaustive over all 64 email outcomes, the whole web ladder (W0 to W9 strictly falls), and 300 random web chains.
* **Floor holds:** any scan that returns every always-sent field scores at least the floor; the fully hardened profiles score exactly the floor.
* **Deterministic:** the same profile gives the same result twice and in any input order.
* **Nothing but statuses moves the score:** extra fields such as \`fixed\`, \`confirmed\`, \`wizard_complete\`, \`from_default\`, \`effort\` and \`bonus\` are ignored.
`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = render();
  if (process.argv.includes('--check')) { if (readFileSync(OUT, 'utf8') !== out) { console.error('docs/exposure-v3-fixtures-mpc-11569.md is stale: run node scripts/exposure-v3-fixtures.mjs'); process.exit(1); } console.log('fixture table is up to date'); }
  else { writeFileSync(OUT, out); console.log(`wrote ${path.relative(ROOT, OUT)}`); }
}
