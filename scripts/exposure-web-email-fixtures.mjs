// MPC-11569 / MPC-11622: the published fixture table for the WEB and EMAIL channels on the shared exposure core (rules page section 8: "Publish the fixture table with the change").
// Synthetic profiles through the real code. Run: node scripts/exposure-web-email-fixtures.mjs   (writes docs/exposure-tier-1-web-email-fixtures.md)   --check exits 1 if stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { scoreWeb, WEB_EXPOSURE } from '../shared/exposure/channels/web.js';
import { scoreEmail, EMAIL_EXPOSURE } from '../shared/exposure/channels/email.js';
import { WEB_FIXTURES, EMAIL_FIXTURES } from '../shared/exposure/channels/webEmail.fixtures.js';
import { NOT_OBSERVABLE_WEB, EMAIL_NOT_BUILT } from '../shared/exposure/channels/scope.generated.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = path.join(ROOT, 'docs/exposure-tier-1-web-email-fixtures.md');
const table = (fixtures, score) => `| # | Profile | Fields returned | Exposure | Position in the range you can change | Fix list |\n|---|---|---|---|---|---|\n${fixtures.map((p) => {
  const r = score(p.items);
  return r.status === 'scored'
    ? `| ${p.id} | ${p.name} | ${r.countText} | ${r.score} | ${r.position.belowFloor ? '0% (below floor)' : `${r.position.percent}%`} | ${r.recoverable.text} |`
    : `| ${p.id} | ${p.name} | not enough observed | no score | n/a | n/a |`;
}).join('\n')}`;
export function render() {
  const w = WEB_EXPOSURE; const e = EMAIL_EXPOSURE;
  return `# Exposure score \`exposure-tier-1\`: web and email fixture tables (MPC-11569 / MPC-11622)

GENERATED by \`node scripts/exposure-web-email-fixtures.mjs\`. Do not edit by hand. Binding rules: Notion, "MPT > Exposure scoring - the rules for every channel" (decided 2026-11-27). Code: the shared core \`shared/exposure/exposure.js\`; channel definitions \`shared/exposure/channels/web.js\` (scope \`web-scope-1\`) and \`email.js\` (scope \`email-scope-1\`), scope data \`scope.generated.js\` (built by \`scripts/build-exposure-scope.mjs\` from the registry and the approved risk tiers). Profiles are synthetic, in \`shared/exposure/channels/webEmail.fixtures.js\`. The score is within-channel only: web and email are never combined.

\`Exposure = round_half_up(100 * tier weight of fields returned / tier weight of all fields in scope)\`, tiers low 1, medium 2, high 3, fixed denominator. A field that did not come back stays in the denominator at 0. No band is shown: the bands were built for the web score and are not valid for a channel with a floor (rule 7); the position within the range you can change is shown instead.

## Web (${w.total} fields in scope: ${w.baseCount} always sent + ${w.settingsCount} your settings; weight ${w.totalWeight}, always sent ${w.baseWeight}; floor ${w.floor})

${NOT_OBSERVABLE_WEB.length} web hexagons the site can never observe are not in N: ${NOT_OBSERVABLE_WEB.join(', ')}.

${table(WEB_FIXTURES, scoreWeb)}

## Email (${e.total} fields in scope: ${e.baseCount} always sent + ${e.settingsCount} your settings; weight ${e.totalWeight}, always sent ${e.baseWeight}; floor ${e.floor})

Not built, so not scored and not Live: ${Object.entries(EMAIL_NOT_BUILT).map(([id, why]) => `\`${id}\` (${why})`).join(', ')}. An email check whose source was unreachable is not observed, so that report has no score (E10, E11).

${table(EMAIL_FIXTURES, scoreEmail)}

## What the tests assert (\`shared/exposure/channels/webEmail.test.mjs\`)

* Every pinned score equals the engine AND an independent oracle written in the test from the tier table alone.
* Monotonic: hardening a setting never raises the score (exhaustive over all 64 email outcomes; the web ladder W0 to W9 strictly falls; 300 random web chains).
* The floor holds, and the fully hardened profiles score exactly the floor (web 76, email 40). Deterministic in any input order.
* Nothing but the observed state moves the score (\`fixed\`, \`confirmed\`, \`wizard_complete\`, \`from_default\`, \`effort\`, \`bonus\` are ignored).
`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = render();
  if (process.argv.includes('--check')) { if (readFileSync(OUT, 'utf8') !== out) { console.error('docs/exposure-tier-1-web-email-fixtures.md is stale: run node scripts/exposure-web-email-fixtures.mjs'); process.exit(1); } console.log('fixture table is up to date'); }
  else { writeFileSync(OUT, out); console.log(`wrote ${path.relative(ROOT, OUT)}`); }
}
