import { judge, main, MAX_AGE_HOURS } from './check.mjs';
let ok = true; const check = (c, m) => { console.log(c ? 'PASS' : 'FAIL', m); if (!c) ok = false; };
const now = new Date('2026-11-04T18:00:00Z');
const ago = (h) => new Date(now.getTime() - h * 3600000).toISOString();
check(judge({ captured_at: ago(2) }, now).ok === true, 'a row 2 hours old is alive');
check(judge({ captured_at: ago(25.9) }, now).ok === true, 'just inside the limit is alive');
check(judge({ captured_at: ago(26.5) }, now).ok === false, 'a row older than the limit is dead');
check(judge({ captured_at: ago(150) }, now).ok === false && /150/.test(judge({ captured_at: ago(150) }, now).reason), 'six days of silence is dead and the age is named');
check(judge(null, now).ok === false && judge({}, now).ok === false, 'no row at all is dead');
check(judge({ captured_at: 'garbage' }, now).ok === false, 'an unreadable time is dead, not a pass');
check(MAX_AGE_HOURS === 26, 'limit is one missed daily run plus slack');
const env = { SUPABASE_URL: 'https://x.supabase.co', SUPABASE_SERVICE_ROLE_KEY: 'sekret-key' };
const logs = []; const log = (m) => logs.push(m);
const respond = (rows, status = 200) => async (url, opts) => { respond.last = { url: String(url), opts }; return { ok: status < 400, status, json: async () => rows }; };
check(await main(env, now, respond([{ captured_at: ago(3) }]), log) === 0, 'main: exit 0 when fresh');
check(respond.last.url.includes('report=eq.table_counts') && respond.last.url.includes('limit=1') && respond.last.opts.method === undefined, 'main: one read-only GET of the newest row');
check(await main(env, now, respond([{ captured_at: ago(150) }]), log) === 1, 'main: exit 1 when the collector has been silent');
check(await main(env, now, respond([]), log) === 1, 'main: exit 1 when there is no row');
check(await main(env, now, respond([], 500), log) === 1, 'main: exit 1 when the database cannot be read');
check(await main({}, now, respond([]), log) === 2, 'main: exit 2 (not configured) when credentials are missing, never a pass');
check(!logs.join('\n').includes('sekret-key'), 'the key never appears in the output');
process.exit(ok ? 0 : 1);
